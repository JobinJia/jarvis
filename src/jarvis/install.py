def merge_codex_config(existing: str, hook_command: str) -> str:
    """Inject (or replace) our managed hook block in a Codex config.toml.

    TOML constrains where bare top-level keys (like `notify`) may appear:
    they must precede any `[section]` header. We therefore insert our
    block *before* the first section header in the user's file, after
    any existing top-level keys. If the block is already present we
    replace it in place. If there are no section headers we append at
    the end.
    """
    block = _render_codex_block(hook_command)
    if _CODEX_BLOCK_RE.search(existing):
        return _CODEX_BLOCK_RE.sub(block, existing)

    lines = existing.splitlines(keepends=True)
    insert_at = None
    for i, line in enumerate(lines):
        stripped = line.lstrip()
        if stripped.startswith("["):
            insert_at = i
            break
    if insert_at is None:
        # No [section] headers — append (preserve trailing newline)
        sep = "\n" if existing and not existing.endswith("\n") else ""
        return existing + sep + "\n" + block

    # Drop trailing blank lines from the head so we don't accumulate them.
    head = "".join(lines[:insert_at]).rstrip() + "\n\n"
    tail = "".join(lines[insert_at:])
    return head + block + "\n" + tail


def remove_from_codex_config(existing: str) -> str:
    """Strip our managed block from a Codex config.toml; no-op if absent."""
    cleaned = _CODEX_BLOCK_RE.sub("", existing)
    # Collapse the double blank line we may have left behind.
    return re.sub(r"\n{3,}", "\n\n", cleaned)


def render_plist(label: str, program: str, log_dir: str, env: dict[str, str]) -> str:
    """Render a launchd plist for the daemon."""
    env_xml = "\n".join(
        f"        <key>{k}</key>\n        <string>{v}</string>"
        for k, v in env.items()
    )
    return textwrap.dedent(
        f"""\
        <?xml version="1.0" encoding="UTF-8"?>
        <!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
        <plist version="1.0">
        <dict>
            <key>Label</key>
            <string>{label}</string>
            <key>ProgramArguments</key>
            <array>
                <string>{program}</string>
            </array>
            <key>RunAtLoad</key>
            <true/>
            <key>KeepAlive</key>
            <true/>
            <key>StandardOutPath</key>
            <string>{log_dir}/daemon.stdout.log</string>
            <key>StandardErrorPath</key>
            <string>{log_dir}/daemon.stderr.log</string>
            <key>EnvironmentVariables</key>
            <dict>
{env_xml}
            </dict>
        </dict>
        </plist>
        """
    )


