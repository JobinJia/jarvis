        # topic_notify = "<long-random-secret-1>"
        # topic_reply = "<long-random-secret-2>"
        # events = ["permission_prompt", "ask_user_question", "elicitation_dialog"]
        # # Shell bridge run per decision with JARVIS_SESSION_ID /
